import {build} from 'esbuild';
import assert from 'node:assert/strict';
const bundle=await build({entryPoints:['server/core.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const {mutate}=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const empty=()=>({customers:[],employees:[],products:[],entries:[],orders:[],closes:[],audit:[],orderSeq:0,invoiceSeq:0,users:[]});
const source={...empty(),customers:[{id:'c1',name:'عميل',opening:20}],entries:[{id:'e1',kind:'sale',person:'c1',amount:100,cash:30,insta:20,vodafone:0,invoiceNo:7,items:[{name:'منتج',qty:1,price:100}]}],orders:[{id:'o1',orderNo:8}]};
const backup={format:'hakim-ledger-backup',version:1,state:source};
const actor={id:'admin1',role:'admin',name:'Admin',username:'admin'};
const current={...empty(),customers:[{id:'old'}],entries:[{id:'old-entry'}]};
const run=(data,user=actor)=>mutate(structuredClone(current),{action:'restoreLedger',data},user);
const restored=run({state:backup,confirmation:'استرجاع'});
assert.deepEqual(restored.entries,source.entries);assert.equal(restored.invoiceSeq,7);assert.equal(restored.orderSeq,8);assert.equal(restored.customers[0].id,'c1');assert.equal(restored.audit.at(-1).action,'restoreLedger');
assert.deepEqual(run({state:source,confirmation:'استرجاع'}).entries,source.entries);
assert.throws(()=>run({state:backup,confirmation:'استرجاع'},{...actor,role:'cashier'}));
assert.throws(()=>run({state:backup,confirmation:''}));
assert.throws(()=>run({state:{...backup,version:2},confirmation:'استرجاع'}));
assert.throws(()=>run({state:{...source,entries:[...source.entries,...source.entries]},confirmation:'استرجاع'}));
assert.throws(()=>run({state:{...source,entries:[{id:'x',amount:-1}]},confirmation:'استرجاع'}));
assert.throws(()=>mutate(structuredClone(current),{action:'importLedger',data:{state:source}},actor));
assert.deepEqual(current.entries,[{id:'old-entry'}]);
console.log('Backup tests passed: round trip, legacy files, replacement, sequences, roles, confirmation, malformed files, duplicate IDs.');
